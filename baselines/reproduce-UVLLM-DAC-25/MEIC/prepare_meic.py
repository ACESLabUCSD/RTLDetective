#!/usr/bin/env python3
"""Build the UVLLM "MEIC" benchmark from verilog_debug/testset/MEIC_Testset.

Source layout (read-only, never modified):
    <src>/<design>/<design>.v                  golden RTL
    <src>/<design>/design_description.txt      spec
    <src>/<design>/benchmarks/tb.v             testbench (DUT instance is `uut`)
    <src>/<design>/buggy/<design>_<bug>.v      buggy variants

Generated layout (next to this script), matching ErrorSet:
    MEIC/MEIC.conf                             UVLLM bug config, sections <design>_<N>
    MEIC/bug_map.json                          <design>_<N> -> original MEIC bug file name
    MEIC/<design>/<design>.v
    MEIC/<design>/design_description.txt
    MEIC/<design>/testbench.v                  tb.v + $dumpfile("test.vcd") / test.txt
    MEIC/<design>/<design>_buggy<N>.v

Buggy files are copied, not linked, because UVLLM rewrites `src_file` in place
and writes simulation outputs into the project directory.

Usage:
    python MEIC/prepare_meic.py                 # default source path
    python MEIC/prepare_meic.py --src /path/to/MEIC_Testset
    python MEIC/prepare_meic.py --force         # rebuild, discarding UVLLM edits
"""
import argparse, json, os, re, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SRC = os.path.normpath(os.path.join(HERE, "..", "..", "..", "testset", "MEIC_Testset"))

TB_HOOK = """
    // ---- added by prepare_meic.py for UVLLM (VCD-based mismatch detection) ----
    initial begin
        $dumpfile("test.vcd");
        $dumpvars(0, uut);
    end
    integer uvllm_f_log;
    initial begin
        uvllm_f_log = $fopen("test.txt", "w");
        $fclose(uvllm_f_log);
    end
    // ---------------------------------------------------------------------------
"""


def adapt_testbench(tb_src):
    m = re.search(r"^\s*module\s+(\w+)", tb_src, re.M)
    if not m:
        raise ValueError("no module in testbench")
    end = re.search(r"^\s*endmodule\b", tb_src[m.end():], re.M)
    if not end:
        raise ValueError("no endmodule for testbench top")
    pos = m.end() + end.start()
    return tb_src[:pos] + TB_HOOK + tb_src[pos:]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=DEFAULT_SRC, help="MEIC_Testset directory")
    ap.add_argument("--force", action="store_true", help="overwrite existing design folders")
    args = ap.parse_args()

    src = os.path.abspath(args.src)
    if not os.path.isdir(src):
        sys.exit(f"MEIC_Testset not found: {src}")

    conf_lines = ["# Generated by prepare_meic.py from verilog_debug/testset/MEIC_Testset", ""]
    bug_map = {}
    designs = sorted(d for d in os.listdir(src) if os.path.isdir(os.path.join(src, d)))

    for design in designs:
        sdir = os.path.join(src, design)
        golden = os.path.join(sdir, f"{design}.v")
        spec = os.path.join(sdir, "design_description.txt")
        tb = os.path.join(sdir, "benchmarks", "tb.v")
        bdir = os.path.join(sdir, "buggy")
        if not all(os.path.exists(p) for p in (golden, spec, tb, bdir)):
            print(f"skip {design}: missing golden/spec/tb/buggy", file=sys.stderr)
            continue

        ddir = os.path.join(HERE, design)
        if os.path.exists(ddir):
            if not args.force:
                print(f"keep {design}: already built (use --force to rebuild)")
            else:
                shutil.rmtree(ddir)
        built_now = not os.path.exists(ddir)
        if built_now:
            os.makedirs(ddir)
            shutil.copy2(golden, os.path.join(ddir, f"{design}.v"))
            shutil.copy2(spec, os.path.join(ddir, "design_description.txt"))
            with open(tb) as f:
                tb_text = adapt_testbench(f.read())
            with open(os.path.join(ddir, "testbench.v"), "w") as f:
                f.write(tb_text)

        bugs = sorted(b for b in os.listdir(bdir) if b.endswith(".v"))
        for i, bug in enumerate(bugs, 1):
            dst = f"{design}_buggy{i}.v"
            if built_now:
                shutil.copy2(os.path.join(bdir, bug), os.path.join(ddir, dst))
            key = f"{design}_{i}"
            bug_map[key] = bug
            rel = f"MEIC/{design}"
            conf_lines += [
                f"# {bug}",
                f"[{key}]",
                f'src_file=["{rel}/{dst}"]',
                f"test_bench={rel}/testbench.v",
                f"orig_file={rel}/{design}.v",
                f"proj_dir={rel}",
                f"oracle_output={rel}/oracle_tb.txt",
                f"sim_output={rel}/test.txt",
                f"oracle_vcd={rel}/oracle_tb.vcd",
                f"sim_vcd={rel}/test.vcd",
                f"spec_file={rel}/design_description.txt",
                "include_list=[]",
                "define_list=[]",
                f'top_module={{"{design}":["uut"]}}',
                "",
            ]
        print(f"{design}: {len(bugs)} bugs")

    with open(os.path.join(HERE, "MEIC.conf"), "w") as f:
        f.write("\n".join(conf_lines))
    with open(os.path.join(HERE, "bug_map.json"), "w") as f:
        json.dump(bug_map, f, indent=2)
    print(f"{len(bug_map)} bugs from {len(designs)} designs -> {os.path.join(HERE, 'MEIC.conf')}")


if __name__ == "__main__":
    main()
